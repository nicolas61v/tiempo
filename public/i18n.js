export const LANGS = ['en', 'es'];
const KEY = 'tiempo.lang';

function readLang() {
  try {
    const l = globalThis.localStorage?.getItem(KEY);
    return LANGS.includes(l) ? l : 'en';
  } catch {
    return 'en';
  }
}

export const LANG = readLang();
